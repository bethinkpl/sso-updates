package mq

import (
	"context"
	"fmt"

	"github.com/sirupsen/logrus"
	"github.com/streadway/amqp"
)

const broadcastExchangeName = "sso.updates.broadcast"

// Publishes to the durable fanout RabbitMQ exchange, using a new connection for every message.
type rabbitBroker struct {
	dsn string
	log logrus.FieldLogger
}

// Connect to a given exchange using a temporary queue
//
// Uses a durable, fanout exchange.
//
// @see https://www.rabbitmq.com/tutorials/tutorial-one-go.html
// @see https://pkg.go.dev/github.com/streadway/amqp
func (b *rabbitBroker) connect(exchangeName string) (*amqp.Connection, *amqp.Channel, error) {
	conn, err := amqp.Dial(b.dsn)
	if err != nil {
		b.log.WithError(err).Error("Failed to connect to RabbitMQ")

		return nil, nil, fmt.Errorf("failed to connect to RabbitMQ: %w", err)
	}

	ch, err := conn.Channel()
	if err != nil {
		conn.Close()
		b.log.WithError(err).Error("Failed to open a channel")

		return nil, nil, fmt.Errorf("failed to open a channel: %w", err)
	}

	// @see https://www.rabbitmq.com/tutorials/tutorial-four-go.html
	err = ch.ExchangeDeclare(
		exchangeName, // name
		"fanout",     // type
		true,         // durable
		false,        // delete when unused
		false,        // internal
		false,        // no-wait
		nil,          // arguments
	)
	if err != nil {
		// Errors returned from this method will close the channel.
		// Hence, no ch.Close() call
		conn.Close()
		b.log.WithError(err).Error("Failed to declare an exchange")

		return nil, nil, fmt.Errorf("failed to declare an exchange: %w", err)
	}

	// use a temporary queue with a unique name generated by RabbitMQ
	_, err = ch.QueueDeclare(
		"",    // name
		true,  // durable
		true,  // delete when unused
		true,  // exclusive
		false, // no-wait
		nil,   // arguments
	)
	if err != nil {
		conn.Close()
		b.log.WithError(err).Error("Failed to declare a queue")

		return nil, nil, fmt.Errorf("failed to declare a queue: %w", err)
	}

	b.log.WithField("exchangeName", exchangeName).Debug("Connected to the broker")

	return conn, ch, nil
}

// Broadcast the event via fanout RabbitMQ exchange
func (b *rabbitBroker) Publish(_ context.Context, event Event) error {
	b.log.WithField("exchange", broadcastExchangeName).WithField("payload", string(event.Body)).
		Debug("Broadcasting the message")

	conn, ch, err := b.connect(broadcastExchangeName)
	if err != nil {
		return err
	}

	defer conn.Close()
	defer ch.Close()

	// @see https://www.rabbitmq.com/tutorials/tutorial-three-go.html
	err = ch.Publish(
		broadcastExchangeName,
		"",    // routing key
		false, // mandatory
		false, // immediate
		amqp.Publishing{
			ContentType: "application/json",
			Body:        event.Body,
		})
	if err != nil {
		b.log.WithError(err).Error("Failed to broadcast the message")

		return fmt.Errorf("failed to broadcast the message: %w", err)
	}

	b.log.WithField("payload", string(event.Body)).Info("Broadcasted the message")

	return nil
}

// Nothing to close: every message uses its own connection
func (b *rabbitBroker) Close(context.Context) error {
	return nil
}
